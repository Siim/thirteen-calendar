/**
 * The generated CLDR Windows zone table (docs/EVENTS.md §5.4, §6.1 C7) and its
 * generator, `scripts/windows-zones.ts`.
 */
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { WINDOWS_ZONES } from '../../src/ics/windows-zones.ts';
import { CLDR_TAG, parseWindowsZones, renderWindowsZones } from '../../scripts/windows-zones.ts';
import { zones } from './helpers.ts';

const GENERATED = readFileSync(new URL('../../src/ics/windows-zones.ts', import.meta.url), 'utf8');

describe('src/ics/windows-zones.ts', () => {
  it('holds every golden zone once, sorted by Windows id', () => {
    const ids = WINDOWS_ZONES.map(([windows]) => windows);
    expect(ids.length).toBeGreaterThan(130);
    expect(new Set(ids).size).toBe(ids.length);
    expect([...ids].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))).toEqual(ids);
  });

  it('maps only to zones Node knows', () => {
    expect(WINDOWS_ZONES.filter(([, iana]) => !zones.isKnown(iana))).toEqual([]);
  });

  it('names its CLDR release and carries the Unicode License v3 notice', () => {
    expect(GENERATED).toContain(`CLDR ${CLDR_TAG}`);
    expect(GENERATED).toContain('UNICODE LICENSE V3');
    expect(GENERATED).toContain('SPDX-License-Identifier: Unicode-3.0');
    expect(GENERATED).toContain('Generated by `scripts/windows-zones.ts`');
  });
});

describe('scripts/windows-zones.ts', () => {
  const sample = (rows: string) => `<supplementalData><windowsZones><mapTimezones otherVersion="7e11800" typeVersion="2021a">${rows}</mapTimezones></windowsZones></supplementalData>`;
  const many = Array.from({ length: 100 }, (_, i) => `<mapZone other="Zone ${String(i).padStart(3, '0')}" territory="001" type="Etc/GMT"/>`).join('');

  it('keeps the territory 001 zone of each Windows id, the first of several types', () => {
    const xml = sample(
      `${many}<mapZone other="B Standard Time" territory="001" type="Europe/Kiev"/><mapZone other="B Standard Time" territory="FI" type="Europe/Helsinki"/><mapZone other="A Standard Time" territory="001" type="America/Edmonton America/Cambridge_Bay"/>`,
    );
    const { version, entries } = parseWindowsZones(xml);
    expect(version).toBe('otherVersion 7e11800, typeVersion 2021a');
    expect(entries.slice(0, 2)).toEqual([
      ['A Standard Time', 'America/Edmonton'],
      ['B Standard Time', 'Europe/Kiev'],
    ]);
  });

  it('rejects a text that is not the table', () => {
    expect(() => parseWindowsZones('<html></html>')).toThrow();
  });

  it('renders the module it generated', () => {
    const xml = sample(WINDOWS_ZONES.map(([windows, iana]) => `<mapZone other="${windows}" territory="001" type="${iana}"/>`).join(''));
    const license = GENERATED.slice(GENERATED.indexOf(' * UNICODE LICENSE V3'), GENERATED.indexOf(' * @internal'))
      .split('\n')
      .map((line) => line.replace(/^ \*( |$)/, ''))
      .join('\n');
    expect(renderWindowsZones(xml, license)).toBe(GENERATED);
  });
});
