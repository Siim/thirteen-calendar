/**
 * Generates `src/ics/windows-zones.ts`, the Windows time zone id to IANA id
 * table of the `.ics` reader (docs/EVENTS.md §5.4, §6.1 C7), from the CLDR
 * `windowsZones` supplemental data (Unicode License v3).
 *
 * Usage (from packages/core):
 *
 *     node scripts/windows-zones.ts
 *     node scripts/windows-zones.ts --from <windowsZones.xml> --license <LICENSE>
 *
 * Without `--from` the script downloads both files of the pinned CLDR release
 * {@link CLDR_TAG} from GitHub. Each Windows id maps to its `territory="001"`
 * zone (CLDR's golden zone). The output is deterministic: entries are sorted
 * by Windows id in code point order.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** The CLDR release the table is generated from. */
export const CLDR_TAG = 'release-48-2';
const BASE = `https://raw.githubusercontent.com/unicode-org/cldr/${CLDR_TAG}/`;
const OUTPUT = new URL('../src/ics/windows-zones.ts', import.meta.url);

/** The `territory="001"` mappings of a `windowsZones.xml`, sorted by Windows id. */
export function parseWindowsZones(xml: string): { version: string; entries: [string, string][] } {
  const header = /<mapTimezones\s+otherVersion="([^"]*)"\s+typeVersion="([^"]*)"/.exec(xml);
  const version = header === null ? 'unknown' : `otherVersion ${header[1]}, typeVersion ${header[2]}`;
  const entries = new Map<string, string>();
  for (const match of xml.matchAll(/<mapZone\s+other="([^"]+)"\s+territory="([^"]+)"\s+type="([^"]+)"\s*\/>/g)) {
    const [, other, territory, type] = match;
    if (territory !== '001') continue;
    const iana = type!.split(' ')[0]!;
    if (entries.has(other!) && entries.get(other!) !== iana) throw new Error(`Two golden zones for ${other}`);
    entries.set(other!, iana);
  }
  if (entries.size < 100) throw new Error(`Only ${entries.size} Windows zones found; is this windowsZones.xml?`);
  const sorted = [...entries].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return { version, entries: sorted };
}

/** The generated module text. */
export function renderWindowsZones(xml: string, license: string): string {
  const { version, entries } = parseWindowsZones(xml);
  const licenseLines = license
    .replace(/\r\n?/g, '\n')
    .trim()
    .split('\n')
    .map((line) => (line === '' ? ' *' : ` * ${line}`.replaceAll('*/', '* /')));
  const quote = (text: string) => `'${text.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
  const rows = entries.map(([windows, iana]) => `  [${quote(windows)}, ${quote(iana)}],`);
  return [
    '/**',
    ' * Windows time zone ids to IANA ids (docs/EVENTS.md §5.4): the `territory="001"`',
    ` * mappings of the CLDR \`windowsZones\` table, CLDR ${CLDR_TAG} (${version}).`,
    ' * Generated by `scripts/windows-zones.ts`; do not edit by hand.',
    ' *',
    ' * The table is CLDR data, used under the Unicode License v3:',
    ' *',
    ...licenseLines,
    ' * @internal',
    ' * @module',
    ' */',
    '',
    '/** `[Windows id, IANA id]` pairs, sorted by Windows id. */',
    'export const WINDOWS_ZONES: readonly (readonly [string, string])[] = [',
    ...rows,
    '];',
    '',
  ].join('\n');
}

async function fetchText(path: string): Promise<string> {
  const response = await fetch(`${BASE}${path}`);
  if (!response.ok) throw new Error(`GET ${BASE}${path}: ${response.status}`);
  return response.text();
}

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  const option = (name: string): string | null => {
    const index = args.indexOf(name);
    return index < 0 ? null : (args[index + 1] ?? null);
  };
  const from = option('--from');
  const licensePath = option('--license');
  const xml = from === null ? await fetchText('common/supplemental/windowsZones.xml') : readFileSync(from, 'utf8');
  const license = licensePath === null ? await fetchText('LICENSE') : readFileSync(licensePath, 'utf8');
  const text = renderWindowsZones(xml, license);
  writeFileSync(OUTPUT, text, 'utf8');
  console.log(`Wrote ${parseWindowsZones(xml).entries.length} Windows zones to ${fileURLToPath(OUTPUT)}`);
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  await main();
}
