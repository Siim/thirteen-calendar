/**
 * Writes `src/primitives/glyphs.ts`: the path data of the Phosphor icons that
 * Thirteen uses, in the one weight each is drawn in.
 *
 * Each `@phosphor-icons/react` icon module carries all six weights (thin,
 * light, regular, bold, fill, duotone) as React elements, plus the shared
 * IconBase and its context, so every icon cost the bundle about 2.8 kB of
 * JavaScript of which one sixth was ever drawn. The app now ships only the
 * paths below, and `@phosphor-icons/react` is a development dependency of
 * this package: this script reads it, and `glyphs.test.ts` checks that the
 * generated file still matches it.
 *
 * To add an icon: add a row to ICONS (name, Phosphor component, weight), run
 * `pnpm --filter @thirteen/ui icons`, then use `<Icon name="..." />`. Phosphor
 * names are listed at https://phosphoricons.com.
 *
 * Usage: node packages/ui/scripts/icons.ts [--check]
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { type ComponentType, createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

type Weight = 'thin' | 'light' | 'regular' | 'bold' | 'fill' | 'duotone';

/** A Phosphor icon component, as far as this script uses it. */
export type PhosphorComponent = ComponentType<{ readonly weight?: Weight }>;

/**
 * Icon name, Phosphor component, weight: exactly the icons the code uses (glyphs.test.ts checks the
 * list against the package; unused rows only add bytes). New rows go at the end, so diffs stay small.
 */
