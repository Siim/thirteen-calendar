export interface RenderedGlyph {
  readonly paths: readonly string[];
}

/** The `d` of every `<path>` the Phosphor component draws in `weight`; throws on anything but plain paths. */
export function phosphorPaths(component: PhosphorComponent, weight: Weight): RenderedGlyph {
  const markup = renderToStaticMarkup(createElement(component, { weight }));
  const inner = /^<svg [^>]*viewBox="0 0 256 256"[^>]*>(.*)<\/svg>$/.exec(markup)?.[1];
  if (inner === undefined) throw new Error(`Unexpected Phosphor markup: ${markup.slice(0, 120)}`);
  const paths: string[] = [];
  const rest = inner.replace(/<path d="([^"]+)"><\/path>/g, (_match, d: string) => {
    paths.push(d);
    return '';
  });
  if (rest !== '' || paths.length === 0) throw new Error(`Only plain <path> elements are supported, got: ${inner.slice(0, 120)}`);
  return { paths };
}

