async function render(): Promise<string> {
  const rows: string[] = [];
  for (const [name, phosphor, weight] of ICONS) {
    const module = (await import(`@phosphor-icons/react/dist/csr/${phosphor}`)) as Record<string, PhosphorComponent | undefined>;
    const component = module[phosphor];
    if (component === undefined) throw new Error(`@phosphor-icons/react has no icon ${phosphor}`);
    const { paths } = phosphorPaths(component, weight);
    rows.push(
      `  ${JSON.stringify(name)}: {\n    phosphor: ${JSON.stringify(phosphor)},\n    weight: ${JSON.stringify(weight)},\n    paths: [\n${paths
        .map((d) => `      ${JSON.stringify(d)},`)
        .join('\n')}\n    ],\n  },`,
    );
  }
  return `${LICENSE}

/** One icon: the Phosphor component and weight it comes from, and its paths on a 256 x 256 grid. */
export interface Glyph {
  readonly phosphor: string;
  readonly weight: 'thin' | 'light' | 'regular' | 'bold' | 'fill' | 'duotone';
  readonly paths: readonly string[];
}

export const GLYPHS = {
${rows.join('\n')}
} as const satisfies Readonly<Record<string, Glyph>>;

export type GlyphName = keyof typeof GLYPHS;
`;
}

// Only when run as a script, not when glyphs.test.ts imports ICONS and phosphorPaths.
if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = await render();
  const current = (() => {
    try {
      return readFileSync(OUT, 'utf8');
    } catch {
      return null;
    }
  })();
  if (process.argv.includes('--check')) {
    if (current !== text) {
      console.error('src/primitives/glyphs.ts is stale: run pnpm --filter @thirteen/ui icons');
      process.exit(1);
    }
    console.log('glyphs.ts is up to date');
  } else if (current === text) {
    console.log('Unchanged src/primitives/glyphs.ts');
  } else {
    writeFileSync(OUT, text);
    console.log(`Wrote src/primitives/glyphs.ts (${ICONS.length} icons)`);
  }
}
