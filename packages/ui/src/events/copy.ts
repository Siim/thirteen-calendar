export type CopyId = keyof typeof COPY;
type StringId = { [K in CopyId]: (typeof COPY)[K] extends string ? K : never }[CopyId];
type PluralId = Exclude<CopyId, StringId>;

/** Fills `{name}` placeholders; a placeholder without a value stays as written. */
export function fill(template: string, values: Readonly<Record<string, string | number>> = {}): string {
  return template.replace(/\{([^{}]+)\}/g, (match, name: string) => {
    const value = values[name];
    return value === undefined ? match : String(value);
  });
}

/** A catalogue string, filled. */
export function copy(id: StringId, values?: Readonly<Record<string, string | number>>): string {
  return fill(COPY[id], values);
}

const rules = new Intl.PluralRules('en-US');

/** A plural catalogue string for `n`, filled (`{n}` is set to `n`). */
export function plural(id: PluralId, n: number, values: Readonly<Record<string, string | number>> = {}): string {
  const forms: PluralCopy = COPY[id];
  return fill(rules.select(n) === 'one' ? forms.one : forms.other, { n, ...values });
}
