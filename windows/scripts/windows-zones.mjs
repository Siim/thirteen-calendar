#!/usr/bin/env node
/**
 * Generates windows/Thirteen.Core/Ics/WindowsZones.g.cs, the C# copy of the CLDR Windows time zone table of
 * the .ics module (docs/EVENTS.md §5.4, §6.4 task W2), from packages/core/src/ics/windows-zones.ts, so that
 * the TypeScript and C# tables stay identical. The TypeScript file is itself generated from CLDR by
 * packages/core/scripts/windows-zones.ts; run that first when the CLDR release changes, then this.
 *
 * Usage (from the repository root):
 *
 *     node windows/scripts/windows-zones.mjs           writes the C# file
 *     node windows/scripts/windows-zones.mjs --check   exits 1 when the C# file differs from what it would write
 *
 * Thirteen.Core.Tests (IcsConformanceTests) also compares both tables entry by entry.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = new URL('../../packages/core/src/ics/windows-zones.ts', import.meta.url);
const OUTPUT = new URL('../Thirteen.Core/Ics/WindowsZones.g.cs', import.meta.url);

/** The header comment (CLDR release and the Unicode License v3 notice) and the `[windows, iana]` rows of the TypeScript table. */
export function readTypeScriptTable(text) {
  const normalized = text.replace(/\r\n?/g, '\n');
  const headerEnd = normalized.indexOf('*/');
  if (!normalized.startsWith('/**') || headerEnd < 0) throw new Error('windows-zones.ts has no header comment');
  const header = normalized
    .slice(3, headerEnd)
    .split('\n')
    .map((line) => line.replace(/^ \*( |$)/, ''))
    .filter((line) => !line.startsWith('@internal') && !line.startsWith('@module'));
  while (header.length > 0 && header[0].trim() === '') header.shift();
  while (header.length > 0 && header[header.length - 1].trim() === '') header.pop();
  const rows = [];
  const row = /^\s*\['((?:[^'\\]|\\.)*)', '((?:[^'\\]|\\.)*)'\],$/;
  const unescape = (s) => s.replace(/\\(.)/g, '$1');
  let inTable = false;
  for (const line of normalized.split('\n')) {
    if (line.startsWith('export const WINDOWS_ZONES')) {
      inTable = true;
      continue;
    }
    if (!inTable) continue;
    if (line.startsWith('];')) break;
    const match = row.exec(line);
    if (match === null) throw new Error(`Unexpected line in WINDOWS_ZONES: ${line}`);
    rows.push([unescape(match[1]), unescape(match[2])]);
  }
  if (rows.length < 100) throw new Error(`Only ${rows.length} rows read from windows-zones.ts`);
  return { header, rows };
}

const csString = (s) => `"${s.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;

/** The C# file text. */
export function renderCSharp(text) {
  const { header, rows } = readTypeScriptTable(text);
  const comment = header.map((line) => (line === '' ? '//' : `// ${line}`));
  return [
    '// <auto-generated>',
    '// Generated by windows/scripts/windows-zones.mjs from packages/core/src/ics/windows-zones.ts; do not edit by hand.',
    '// </auto-generated>',
    '//',
    ...comment,
    '',
    'namespace Thirteen.Core.Ics;',
    '',
    '/// <summary>',
    '/// Windows time zone ids to IANA ids: the <c>territory="001"</c> mappings of the CLDR <c>windowsZones</c> table,',
    '/// the same rows as <c>WINDOWS_ZONES</c> in <c>packages/core/src/ics/windows-zones.ts</c> (docs/EVENTS.md §5.4).',
    '/// </summary>',
    'internal static class WindowsZones',
    '{',
    '    /// <summary><c>(Windows id, IANA id)</c> pairs, sorted by Windows id.</summary>',
    '    public static readonly (string Windows, string Iana)[] Table =',
    '    [',
    ...rows.map(([windows, iana]) => `        (${csString(windows)}, ${csString(iana)}),`),
    '    ];',
    '}',
    '',
  ].join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const text = renderCSharp(readFileSync(SOURCE, 'utf8'));
  if (check) {
    let current = '';
    try {
      current = readFileSync(OUTPUT, 'utf8');
    } catch {
      current = '';
    }
    if (current !== text) {
      console.error(`${fileURLToPath(OUTPUT)} is out of date; run node windows/scripts/windows-zones.mjs`);
      process.exit(1);
    }
    console.log(`${fileURLToPath(OUTPUT)} is up to date`);
    return;
  }
  writeFileSync(OUTPUT, text, 'utf8');
  console.log(`Wrote ${readTypeScriptTable(readFileSync(SOURCE, 'utf8')).rows.length} Windows zones to ${fileURLToPath(OUTPUT)}`);
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) main();
