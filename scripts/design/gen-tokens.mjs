// An always-dark theme passes its dark palette as `light` too (see `resolved`), so it comes out as
// dynamic(light: X, dark: X). Kept in that form rather than a plain Color so the Apple "Design rules"
// tests, which read this file, check the always-dark themes like the others.
function swiftColor(light, dark) {
  const args = [`light: 0x${hex6(light.color)}`, `dark: 0x${hex6(dark.color)}`];
  if (light.color.alpha < 1) args.push(`lightAlpha: ${alphaText(light.color.alpha)}`);
  if (dark.color.alpha < 1) args.push(`darkAlpha: ${alphaText(dark.color.alpha)}`);
  return `dynamic(${args.join(', ')})`;
}

