// ---------------------------------------------------------------------------------------------
// Shared helpers

const camel = (role) =>
  ({ 'ink-2': 'inkSecondary', 'ink-3': 'inkTertiary' })[role] ?? role.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const pascal = (role) => camel(role).replace(/^[a-z]/, (c) => c.toUpperCase());
const titleCase = (id) => id.replace(/^[a-z]/, (c) => c.toUpperCase());

/** Alpha as the shortest decimal that round-trips to 4 places: 0.12, 0.1, 0.55. */
const alphaText = (alpha) => String(Number(alpha.toFixed(4)));
const hex6 = (color) => color.hex.slice(1).toUpperCase();
const byte = (alpha) => Math.round(alpha * 255);

/**
 * Every theme as { id, theme, scheme, alwaysDark, light, dark } resolved for one platform. An
 * always-dark theme has only a dark map, so its `light` is the same resolved dark palette.
 */
function resolved(tokens, platform) {
  return Object.entries(tokens.themes).map(([id, theme]) => ({
    id,
    theme,
    scheme: themeScheme(theme),
    alwaysDark: isAlwaysDark(theme),
    light: resolveTheme(tokens, id, 'light', platform),
    dark: resolveTheme(tokens, id, 'dark', platform),
  }));
}

/**
 * The groups Settings shows, in order, as { scheme, name, description, ids }. Every scheme is a
 * group, even one without themes, so the generated APIs stay the same.
 */
function groups(tokens) {
  return SCHEMES.map((scheme) => ({
    scheme,
    name: tokens.schemes[scheme].name,
    description: tokens.schemes[scheme].description,
    ids: Object.keys(tokens.themes).filter((id) => themeScheme(tokens.themes[id]) === scheme),
  }));
}

/** Wraps text in `// ` (or another prefix) comment lines at about `width` columns. */
function wrapComment(text, prefix, width = 100) {
  const words = text.split(/\s+/);
  const lines = [];
  let line = prefix;
  for (const word of words) {
    if (line.length + word.length + 1 > width && line.trim() !== prefix.trim()) {
      lines.push(line.trimEnd());
      line = prefix;
    }
    line += (line === prefix ? '' : ' ') + word;
  }
  lines.push(line.trimEnd());
  return lines.join('\n');
}

