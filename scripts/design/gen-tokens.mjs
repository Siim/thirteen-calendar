// Web: CSS custom properties

/** The roles that become --t-<role> colour variables. grain and shadow are folded into --t-grain and --t-shadow-N. */
const CSS_SKIP = new Set(['grain', 'shadow']);

const cssColor = (color, alpha = color.alpha) =>
  alpha >= 1 ? color.hex : `rgb(${color.r} ${color.g} ${color.b} / ${alphaText(alpha)})`;

function cssRoleValue(role, light, dark) {
  const l = light[role];
  const d = dark[role];
  if (l.ref && l.ref === d.ref && !CSS_SKIP.has(l.ref)) return `var(--t-${l.ref})`;
  const lv = cssColor(l.color);
  const dv = cssColor(d.color);
  return lv === dv ? lv : `light-dark(${lv}, ${dv})`;
}

function grainUrl(tint) {
  const f = (c) => (c / 255).toFixed(2);
  return (
    `url("data:image/svg+xml;utf8,<svg xmlns='http://www.w3.org/2000/svg' width='240' height='240'>` +
    `<filter id='n'><feTurbulence type='fractalNoise' baseFrequency='.9' numOctaves='3' stitchTiles='stitch'/>` +
    `<feColorMatrix values='0 0 0 0 ${f(tint.r)}  0 0 0 0 ${f(tint.g)}  0 0 0 0 ${f(tint.b)}  0 0 0 0.9 0'/></filter>` +
    `<rect width='100%' height='100%' filter='url(%23n)'/></svg>")`
  );
}

function modeEffects(tokens, palette, mode) {
  const lines = [];
  for (const [name, spec] of Object.entries(tokens.shadows)) {
    if (name.startsWith('$')) continue;
    const { geometry, alpha } = spec[mode];
    const shadow = palette.shadow.color;
    lines.push(`--t-${name}: ${geometry} ${cssColor(shadow, shadow.alpha * alpha)};`);
  }
  lines.push(`--t-grain: ${grainUrl(palette.grain.color)};`);
  return lines;
}

/**
 * What tokens.css sets for dark mode besides colour-scheme: the paper grain is screened and fainter
 * on a dark page. An always-dark theme sets the same values itself, since data-theme may say light.
 */
const CSS_DARK_GRAIN = ['--t-grain-opacity: 0.06;', '--t-grain-blend: screen;'];

function generateWeb(tokens) {
  const roles = Object.keys(tokens.roles).filter((r) => !CSS_SKIP.has(r));
  const themes = resolved(tokens, 'web');
  const ids = themes.map((t) => t.id);
  const darkIds = themes.filter((t) => t.alwaysDark).map((t) => t.id);
  const indent = (lines, n) => lines.map((l) => ' '.repeat(n) + l).join('\n');
  const out = [];
  const darkNote = darkIds.length
    ? `\n *\n${wrapComment(
        `Always-dark themes (${darkIds.join(', ')}) set color-scheme: dark and plain colours on their own selector, so they stay dark whatever data-theme or the OS says. That selector has the same specificity as tokens.css's [data-theme] rules and comes later, which is why this file is imported after it.`,
        ' * ',
      )}`
    : '';
  out.push(`/*
 * ${HEADER}.
 *
 * Colour themes for @thirteen/ui: ${themes.map((t) => `${t.theme.name} (${t.id})`).join(', ')}.
 * Import after tokens.css. ${titleCase(tokens.defaultTheme)} (the default) is on :root; the others apply with
 * data-palette on <html>, e.g. <html data-palette="${ids.find((i) => i !== tokens.defaultTheme) ?? ids[0]}">.
 *
 * Light and dark come from light-dark(), which follows color-scheme (tokens.css sets it from the OS
 * or from data-theme). Shadows and the paper grain are whole values, not colours, so each theme
 * sets them again for dark mode in the same two places tokens.css does.${darkNote}
 */`);

  for (const { id, theme, alwaysDark, light, dark } of themes) {
    const isDefault = id === tokens.defaultTheme;
    const sel = isDefault ? ':root' : `:root[data-palette='${id}']`;
    if (alwaysDark) {
      // One palette, no light-dark(): passing the dark palette for both modes gives plain values.
      const decls = roles.map((role) => `--t-${role}: ${cssRoleValue(role, dark, dark)};`);
      out.push(
        `\n/* ${theme.name}: ${theme.description} */\n${sel} {\n${indent(
          ['color-scheme: dark;', ...decls, ...modeEffects(tokens, dark, 'dark'), ...CSS_DARK_GRAIN],
          2,
        )}\n}`,
      );
      continue;
    }
    const decls = roles.map((role) => `--t-${role}: ${cssRoleValue(role, light, dark)};`);
    out.push(
      `\n/* ${theme.name}: ${theme.description}${isDefault ? ' Default.' : ''} */\n${sel} {\n${indent(
        [...decls, ...modeEffects(tokens, light, 'light')],
        2,
      )}\n}`,
    );
    const darkEffects = modeEffects(tokens, dark, 'dark');
    out.push(`\n${sel}[data-theme='dark'] {\n${indent(darkEffects, 2)}\n}`);
    out.push(`\n@media (prefers-color-scheme: dark) {\n  ${sel}:not([data-theme]) {\n${indent(darkEffects, 4)}\n  }\n}`);
  }
  return `${out.join('\n')}\n`;
}

