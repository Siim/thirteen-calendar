// CLI

function parseArgs(argv) {
  const args = { targets: Object.keys(TARGETS), outDir: REPO_ROOT, check: false, tokens: TOKENS_PATH };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    const value = () => {
      const v = argv[++i];
      if (v === undefined) throw new Error(`${arg} needs a value`);
      return v;
    };
    if (arg === '--targets') args.targets = value().split(',').map((t) => t.trim()).filter(Boolean);
    else if (arg.startsWith('--targets=')) args.targets = arg.slice(10).split(',').map((t) => t.trim()).filter(Boolean);
    else if (arg === '--out-dir') args.outDir = resolve(value());
    else if (arg.startsWith('--out-dir=')) args.outDir = resolve(arg.slice(10));
    else if (arg === '--tokens') args.tokens = resolve(value());
    else if (arg === '--check') args.check = true;
    else if (arg === '--help' || arg === '-h') {
      console.log('Usage: node scripts/design/gen-tokens.mjs [--targets web,apple,android,windows] [--out-dir dir] [--check]');
      process.exit(0);
    } else throw new Error(`Unknown argument ${arg}`);
  }
  const unknown = args.targets.filter((t) => !(t in TARGETS));
  if (unknown.length > 0) throw new Error(`Unknown target(s) ${unknown.join(', ')}; use ${Object.keys(TARGETS).join(', ')}`);
  return args;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const tokens = loadTokens(args.tokens);
  let stale = 0;
  for (const target of args.targets) {
    const { path, generate } = TARGETS[target];
    const file = resolve(args.outDir, path);
    const content = generate(tokens);
    const rel = relative(process.cwd(), file);
    const shown = rel && !rel.startsWith('..') ? rel : file;
    if (args.check) {
      const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
      if (current !== content) {
        stale++;
        console.log(`${target.padEnd(8)} ${shown}: ${current === null ? 'missing' : 'out of date'}`);
      } else console.log(`${target.padEnd(8)} ${shown}: up to date`);
      continue;
    }
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
    console.log(`${target.padEnd(8)} ${shown}`);
  }
  if (stale > 0) {
    console.log(`\n${stale} file(s) need \`pnpm tokens\`.`);
    process.exit(1);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    main();
  } catch (error) {
    console.error(error.message);
    process.exit(2);
  }
}
