function csColor(entry) {
  const c = entry.color;
  const h = (n) => `0x${n.toString(16).toUpperCase().padStart(2, '0')}`;
  return c.alpha < 1
    ? `Color.FromArgb(${h(byte(c.alpha))}, ${h(c.r)}, ${h(c.g)}, ${h(c.b)})`
    : `Color.FromRgb(${h(c.r)}, ${h(c.g)}, ${h(c.b)})`;
}

