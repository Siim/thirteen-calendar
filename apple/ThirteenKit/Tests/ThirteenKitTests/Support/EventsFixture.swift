import Foundation
import ThirteenKit

// Loads fixtures/events.json (format version 1, docs/EVENTS.md §5.5, fixtures/README.md) in place
// from the repository, and provides the zone resolvers its sections replay through: the
// `RecordedZoneResolver` built from `zoneOffsets` alone (for `untils`, `series` and
// `alarmInstants`), and the synthetic resolver of each `zoneMath` case.

struct EventsFixture: Sendable {
    let raw: [String: JSONValue]

    static let shared: Result<EventsFixture, any Error> = Result {
        if let path = overridePath { return try load(URL(fileURLWithPath: path)) }
        let url = try Repository.root().appendingPathComponent("fixtures/events.json")
        return try load(url)
    }

    /// `THIRTEEN_EVENTS_FIXTURE`: replay another file of the same format instead of
    /// fixtures/events.json (differential runs against cases generated by the TypeScript engine;
    /// the envelope and count checks then fail by design).
    static var overridePath: String? { ProcessInfo.processInfo.environment["THIRTEEN_EVENTS_FIXTURE"] }

    /// A file in the format of fixtures/events.json, read from `url`.
    static func load(_ url: URL) throws -> EventsFixture {
        guard case let .object(raw) = try JSONDecoder().decode(JSONValue.self, from: try Data(contentsOf: url)) else {
            throw FixtureError.unexpectedShape("events.json top level is not an object")
        }
        return EventsFixture(raw: raw)
    }

    static func load() throws -> EventsFixture { try shared.get() }

    func cases(_ name: String) throws -> [JSONValue] {
        guard let value = raw[name]?.array else { throw FixtureError.unexpectedShape("events.json section \(name) is not an array") }
        return value
    }

    var tzVersion: String { raw["tzVersion"]?.string ?? "?" }
}

extension JSONValue {
    /// The field `key` of an object case, or a thrown error naming it.
    func field(_ key: String) throws -> JSONValue {
        guard let value = self[key] else { throw FixtureError.unexpectedShape("missing field \(key) in \(self)") }
        return value
    }

    func decode<T: Decodable>(_ key: String, as type: T.Type = T.self) throws -> T {
        try field(key).decode(T.self)
    }

    var isNull: Bool { self == .null }

    var bool: Bool? {
        if case let .bool(value) = self { return value }
        return nil
    }
}

/// A `"YYYY-MM-DD"` fixture date.
func fixtureDate(_ value: JSONValue) throws -> GregorianDate {
    guard let text = value.string else { throw FixtureError.unexpectedShape("expected a date string, got \(value)") }
    return try GregorianDate(isoString: text)
}

/// A `"YYYY-MM-DDTHH:MM"` fixture wall clock.
func fixtureLocal(_ value: JSONValue) throws -> LocalDateTime {
    guard let text = value.string else { throw FixtureError.unexpectedShape("expected a wall clock string, got \(value)") }
    return try LocalDateTime(iso: text)
}

/// A wall clock as fixture JSON (`null` for `nil`).
func fixtureJSON(_ value: LocalDateTime?) -> JSONValue { value.map { .string($0.isoString) } ?? .null }

/// A date as fixture JSON (`null` for `nil`).
func fixtureJSON(_ value: GregorianDate?) -> JSONValue { value.map { .string($0.isoString) } ?? .null }

/// Absolute minutes of a wall clock (Julian Day Number x 1440 + minute), as the engine counts them.
func absoluteMinutes(_ value: LocalDateTime) -> Int { value.date.julianDayNumber * 1440 + value.minute }

/// The test resolver of fixtures/README.md: it answers from the `zoneOffsets` entries alone, knows
/// exactly the zones they list, and throws for a known zone in a UTC year the table does not hold,
/// so no expectation falls back to the platform's tzdata.
struct RecordedZoneResolver: ZoneResolver {
    struct Year: Sendable {
        let start: Int
        let transitions: [(at: Int, offset: Int)]
    }

    let table: [String: [Int: Year]]

    init(_ entries: [JSONValue]) throws {
        var table: [String: [Int: Year]] = [:]
        for entry in entries {
            guard let zone = try entry.field("zone").string, let year = try entry.field("year").int,
                let start = try entry.field("startOffset").int, let transitions = try entry.field("transitions").array
            else { throw FixtureError.unexpectedShape("zoneOffsets entry \(entry)") }
            var parsed: [(at: Int, offset: Int)] = []
            for t in transitions {
                let utc = try fixtureLocal(t.field("utc"))
                guard let offset = try t.field("offset").int, utc.date.year == year else {
                    throw FixtureError.unexpectedShape("zoneOffsets \(zone) \(year) transition \(t)")
                }
                let at = absoluteMinutes(utc)
                if let last = parsed.last, last.at >= at {
                    throw FixtureError.unexpectedShape("zoneOffsets \(zone) \(year): transitions not ascending")
                }
                parsed.append((at, offset))
            }
            if table[zone]?[year] != nil { throw FixtureError.unexpectedShape("zoneOffsets holds \(zone) \(year) twice") }
            table[zone, default: [:]][year] = Year(start: start, transitions: parsed)
        }
        self.table = table
    }

    func isKnown(_ tzid: String) -> Bool { table[tzid] != nil }

    func offsetMinutes(_ tzid: String, at utc: LocalDateTime) throws(ThirteenError) -> Int {
        guard let years = table[tzid] else { throw .invalidEvent("Unknown time zone \(tzid) (not in zoneOffsets)") }
        guard let year = years[utc.date.year] else {
            throw .invalidEvent("zoneOffsets holds no offsets for \(tzid) in \(utc.date.year) (asked for \(utc.isoString))")
        }
        let at = absoluteMinutes(utc)
        var offset = year.start
        for t in year.transitions {
            if t.at > at { break }
            offset = t.offset
        }
        return offset
    }
}

/// The resolver of one `zoneMath` case: `{name, offset, transitions: [{at, offset}]}`, the offset of
/// the last transition at or before the UTC instant (the initial offset before the first).
struct SyntheticZoneResolver: ZoneResolver {
    let name: String
    let offset: Int
    let transitions: [(at: Int, offset: Int)]

    init(_ zone: JSONValue) throws {
        guard let name = try zone.field("name").string, let offset = try zone.field("offset").int,
            let transitions = try zone.field("transitions").array
        else { throw FixtureError.unexpectedShape("zoneMath zone \(zone)") }
        self.name = name
        self.offset = offset
        var parsed: [(at: Int, offset: Int)] = []
        for t in transitions {
            guard let value = try t.field("offset").int else { throw FixtureError.unexpectedShape("zoneMath transition \(t)") }
            let at = absoluteMinutes(try fixtureLocal(t.field("at")))
            if let last = parsed.last, last.at >= at { throw FixtureError.unexpectedShape("zoneMath transitions not ascending") }
            parsed.append((at, value))
        }
        self.transitions = parsed
    }

    func isKnown(_ tzid: String) -> Bool { tzid == name }

    func offsetMinutes(_ tzid: String, at utc: LocalDateTime) throws(ThirteenError) -> Int {
        guard tzid == name else { throw .invalidEvent("Unknown synthetic zone \(tzid)") }
        let at = absoluteMinutes(utc)
        var current = offset
        for t in transitions {
            if t.at > at { break }
            current = t.offset
        }
        return current
    }
}
